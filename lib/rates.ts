function parse<T>(what: string, schema: z.ZodType<T>, raw: unknown): T {
  const result = schema.safeParse(raw);
  if (!result.success) throw new Error(`Invalid data in ${what}:\n${z.prettifyError(result.error)}`);
  return result.data;
}

/** Every published schedule the site knows about. Add a line per new transcribed list. */
/**
 * The written page content carries a hand-checked romanisation of every village name, and it wins
 * over the transliteration lib/devanagari.ts produced at import: 378 of the 1,630 slugs differ,
 * nearly all of them corrections (amova to amowa, karaundimaphi to karaundimafi). Applying it here
 * rather than at each caller means the route params, the page registry, every internal link and
 * the lookup by slug all agree by construction. scripts/build-village-redirects.ts writes a 301
 * from each superseded slug, so nothing that was linked breaks.
 *
 * The slug and name come from data/villageSlugs.json, generated by scripts/build-village-index.ts,
 * rather than from the content file itself: this module is reachable from a client component
 * through lib/data and lib/tools, and importing the 20 MB content here put all of it into the
 * browser bundle. The prose lives in lib/village-content.ts, which stays server-side.
 */
function withContentNames(s: RateSchedule): RateSchedule {
  return {
    ...s,
    rows: s.rows.map((row) => {
      const c = (villageSlugs as Record<string, { slug: string; nameEn: string }>)[row.id];
      return c ? { ...row, slug: c.slug, nameEn: c.nameEn } : row;
    }),
  };
}

