/**
 * Villages in a tehsil that share an identical set of rates.
 *
 * The district sets rates by band rather than per village: 1,630 rows across Ayodhya carry only
 * about 600 distinct rate sets, and in the rural tehsils a single set can cover dozens of
 * villages. Listing the rates once with the villages under them says that plainly, where a table
 * of 351 rows repeating the same four figures hides it.
 *
 * Bands are ordered by size, largest first, and a band of one is not a band — those villages are
 * left to the full table above.
 */
export function getRateBands(cityId: string, tehsilId: string): { key: string; rows: RateRow[] }[] {
  const groups = new Map<string, RateRow[]>();
  const roadBands = getRoadBands(cityId);
  for (const row of getRowsByTehsil(cityId, tehsilId)) {
    const key = [
      // Every band this schedule declares, so two rows are only alike when all their columns are.
      ...roadBands.map((b) => row.nonAgri[b.key] ?? "-"),
      row.commercial?.shop ?? "-",
      row.commercial?.office ?? "-",
      row.commercial?.godown ?? "-",
      row.agriLakhPerHa.general ?? "-",
    ].join("|");
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key)!.push(row);
  }
  return [...groups.entries()]
    .filter(([, rows]) => rows.length > 1)
    .map(([key, rows]) => ({ key, rows }))
    .sort((a, b) => b.rows.length - a.rows.length);
}
